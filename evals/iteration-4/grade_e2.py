#!/usr/bin/env python3
"""E2 grader: authoring convergence across 3 independent skill runs, plus the
three iteration-3 honest-limit closures (compiler-first, naming, counted ENC-06)."""
import itertools
import json
import os
import re
import sys

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "e2-authoring", "with_skill")
RUNS = [os.path.join(BASE, f"run-{i}") for i in (1, 2, 3)]


def _read(run: str, *parts: str) -> bytes:
    return open(os.path.join(run, *parts), "rb").read()


def _summary(run: str) -> dict:
    return json.load(open(os.path.join(run, "etl_out", "summary.json")))


def main() -> int:
    result: dict = {}

    # Naming convention (it-3 limit b): identical artifact names across runs.
    expected_names = {"orders_export.etlspec.yaml", "orders_export_pipeline.py"}
    names_ok = all(expected_names <= set(os.listdir(r)) for r in RUNS)
    result["artifact_names_identical"] = f"{sum(expected_names <= set(os.listdir(r)) for r in RUNS)}/3"

    # Compiler-first (it-3 limit a): pipeline generated by compile_spec, not by hand.
    gen = sum(b"GENERATED by etl-spec-compiler" in _read(r, "orders_export_pipeline.py")
              for r in RUNS)
    result["pipeline_compiler_generated"] = f"{gen}/3"

    # Counted ENC-06 repair (it-3 limit c).
    enc06 = sum(any(k.startswith("ENC-06") for k in _summary(r)["warnings_by_type"])
                for r in RUNS)
    result["enc06_repair_counted_in_warnings"] = f"{enc06}/3"

    # Output/summary identity across runs.
    pairs = list(itertools.combinations(RUNS, 2))
    out_id = sum(_read(a, "etl_out", "output.csv") == _read(b, "etl_out", "output.csv")
                 for a, b in pairs)
    sum_id = sum(_summary(a) == _summary(b) for a, b in pairs)
    pipe_id = sum(_read(a, "orders_export_pipeline.py") == _read(b, "orders_export_pipeline.py")
                  for a, b in pairs)
    spec_id = sum(_read(a, "orders_export.etlspec.yaml") == _read(b, "orders_export.etlspec.yaml")
                  for a, b in pairs)
    result["output_value_identity_pairs"] = f"{out_id}/{len(pairs)}"
    result["summary_identity_pairs"] = f"{sum_id}/{len(pairs)}"
    result["pipeline_byte_identity_pairs"] = f"{pipe_id}/{len(pairs)}"
    result["spec_byte_identity_pairs"] = f"{spec_id}/{len(pairs)}"

    # Decision agreement: read the machine-checkable decisions from each summary
    # + spec text (dispositions show up as accounting).
    decisions = []
    for r in RUNS:
        s = _summary(r)
        spec_text = _read(r, "orders_export.etlspec.yaml").decode("utf-8")

        def _policy(key: str) -> str:
            m = re.search(rf"{key}:\s*\{{\s*value:\s*([\w-]+)", spec_text)
            return m.group(1) if m else "<missing>"

        decisions.append({
            "rows_in": s["rows_in"], "rows_out": s["rows_out"],
            "quarantined": s["rows_quarantined"],
            "errors_by_type": s["errors_by_type"],
            "warnings_by_type": s["warnings_by_type"],
            "duplicate_policy": _policy("duplicate_rows"),
            "disposition": _policy("error_disposition"),
            "mojibake_repaired": bool(re.search(r"op:\s*repair_mojibake", spec_text)),
            "footer_skip_rule": bool(re.search(r"(?m)^skip_rows:", spec_text)),
            "date_formats": re.findall(r"formats:\s*\[([^\]]*)\]", spec_text),
        })
    result["duplicate_provenance_labels"] = [
        (re.search(r"duplicate_rows:\s*\{value:\s*\w+,\s*provenance:\s*([\w-]+)",
                   _read(r, "orders_export.etlspec.yaml").decode()) or [None, "?"])[1]
        for r in RUNS]
    agree = sum(decisions[a] == decisions[b] for a, b in itertools.combinations(range(3), 2))
    result["decision_agreement_pairs"] = f"{agree}/{len(pairs)}"
    result["decisions_run1"] = decisions[0]

    print(json.dumps(result, indent=2))
    ok = (names_ok and gen == 3 and enc06 == 3 and out_id == len(pairs)
          and sum_id == len(pairs) and agree == len(pairs))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
